/**
 * Scenario generator goldens for the Swift generateScenario port (ios/DatumAcoustics ScenarioGen*).
 * Canonical bytes = JSON.stringify(generateScenario(params, seed)) (V8 key insertion order, shortest
 * round-trip numbers, undefined keys dropped, typed arrays as {"0":..} objects).
 *   committed:  Fixtures/golden/scenario-gen.json   (params + sha256 per case, part hashes for a subset, number samples)
 *   gitignored: Fixtures/generated/scenario-gen/<name>.json  (full TS JSON, for byte diffs)
 * Run alone: npx tsx scripts/scenarioGenFixtures.ts   (also run by exportSwiftFixtures.ts)
 */
import {createHash} from 'node:crypto';
import {writeFileSync,mkdirSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {generateScenario,clampParams,presetToParams,type ScenarioParams,type Difficulty} from '../src/scenario/presets.js';
import {catalog} from '../src/catalog/classes.js';

export const SCENARIO_GEN_BEHAVIOURS=[0,.25,.5,.75,1];
const sha=(s:string)=>createHash('sha256').update(s).digest('hex');
const short=(s:string)=>sha(s).slice(0,16);
type Case={name:string;seed:number;params:ScenarioParams};
export function scenarioGenCases():Case[]{
 const out:Case[]=[];
 for(let seed=1;seed<=50;seed++)for(const b of SCENARIO_GEN_BEHAVIOURS)out.push({name:`s${seed}-b${b}`,seed,params:clampParams({seed,behaviour:b})});
 for(const d of ['easy','regular','difficult'] as Difficulty[])for(const seed of [1,7,42])out.push({name:`${d}-${seed}`,seed,params:presetToParams(d,seed)});
 for(const seed of [7,99])out.push({name:`sub12-${seed}`,seed,params:clampParams({seed,subCount:12})});
 return out;
}
/** Part hashes on the parsed tree (order-preserving): top-level minus big arrays, water column, per contact
 * kinematics (minus params) and params, per pool ship likewise. Swift computes the same on its JSON tree. */
export function partHashes(json:string){
 const o=JSON.parse(json);const {contacts,surfacePool,waterColumn,...top}=o;
 const split=(c:any)=>{const {params,...kin}=c;return [short(JSON.stringify(kin)),short(JSON.stringify(params))];};
 return {top:short(JSON.stringify(top)),waterColumn:short(JSON.stringify(waterColumn)),contacts:contacts.map(split),surfacePool:(surfacePool??[]).map(split)};
}
export function exportScenarioGen(fixturesDir:string){
 const GEN=join(fixturesDir,'generated','scenario-gen'),GOLD=join(fixturesDir,'golden');mkdirSync(GEN,{recursive:true});mkdirSync(GOLD,{recursive:true});
 const cases=scenarioGenCases(),nums=new Set<string>();let bytes=0;
 const rows=cases.map((c,i)=>{const json=JSON.stringify(generateScenario(c.params,c.seed));bytes+=json.length;writeFileSync(join(GEN,`${c.name}.json`),json);
  if(i%7===0){const m:string[]=[];const walk=(v:unknown):void=>{if(typeof v==='number')m.push(JSON.stringify(v));else if(v&&typeof v==='object')for(const x of Object.values(v))walk(x);};walk(JSON.parse(json));for(let k=0;k<m.length;k+=97)nums.add(m[k]);}
  const parts=c.seed<=3||!c.name.startsWith('s')?partHashes(json):undefined;
  return {name:c.name,seed:c.seed,params:c.params,bytes:json.length,sha256:sha(json),...(parts?{parts}:{})};});
 // Edge numbers: JS Number::toString switch points and specials.
 const edge=[0,-0,1,-1,0.1,1e-7,1.5e-7,1e-6,123e-20,1e20,1e21,1.5e21,123456789012345680000,2**53,2**53+2,5e-324,1.7976931348623157e308,0.000001,1/3,2/3,100,1e15,1e16,4294967295,-1e-7,3.0000000000000004];
 const numbers=[...edge.map(x=>JSON.stringify(x)),...[...nums]];
 const manifest={note:'Scenario generator goldens (generated by acoustics/scripts/scenarioGenFixtures.ts; do not edit). sha256 over JSON.stringify(generateScenario(params,seed)) bytes; parts = first 16 hex of sha256 (see partHashes). numbers: JS JSON number tokens the Swift writer must reproduce from Double(token).',
  cases:rows,numbers};
 writeFileSync(join(GOLD,'scenario-gen.json'),JSON.stringify(manifest));
 // Class fields the Swift generator needs beyond Resources/catalog.json (randomizeSelection / chooseOperatingState).
 const RES=join(fixturesDir,'..','Sources','DatumAcoustics','Resources');
 writeFileSync(join(RES,'scenario-classes.json'),JSON.stringify({note:'Class fields for the Swift scenario generator (generated by acoustics/scripts/scenarioGenFixtures.ts; do not edit). Order = catalog.classes.',
  classes:catalog.classes.map(k=>({id:k.id,aipCapable:k.aipCapable,aip:k.aip??null,maxSpeedKts:k.maxSpeedKts,quietSpeedKts:k.quietSpeedKts,variants:k.variants.map(v=>v.id)}))}));
 return {cases:rows.length,bytes,numbers:numbers.length};
}
if(process.argv[1]&&fileURLToPath(import.meta.url)===process.argv[1]){
 const r=exportScenarioGen(join(dirname(fileURLToPath(import.meta.url)),'../../ios/DatumAcoustics/Fixtures'));console.log('scenario-gen',JSON.stringify(r));
}
