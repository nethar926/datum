#!/usr/bin/env node
/** Build acoustics/src/wasm/broadband_lloyd.wat → .wasm + base64 TS embed. */
import {readFileSync,writeFileSync,mkdirSync} from 'fs';
import {fileURLToPath} from 'url';
import {dirname,join} from 'path';
import {createRequire} from 'module';
const require=createRequire(import.meta.url);
const wabt=await require('wabt')();
const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const watPath=join(root,'src/wasm/broadband_lloyd.wat');
const wasmPath=join(root,'src/wasm/broadband_lloyd.wasm');
const b64Path=join(root,'src/wasm/broadband_lloyd_b64.ts');
const wat=readFileSync(watPath,'utf8');
const module=wabt.parseWat('broadband_lloyd.wat',wat,{simd:true});
module.resolveNames();
module.validate();
const {buffer}=module.toBinary({log:false});
writeFileSync(wasmPath,Buffer.from(buffer));
const b64=Buffer.from(buffer).toString('base64');
writeFileSync(b64Path,
`/** Auto-generated by scripts/build-wasm.mjs — do not edit. Inline base64 of broadband_lloyd.wasm (SIMD). */\n`+
`export const BROADBAND_LLOYD_WASM_BASE64=${JSON.stringify(b64)};\n`+
`export const BROADBAND_LLOYD_WASM_BYTES=${buffer.byteLength};\n`);
console.log(JSON.stringify({watBytes:wat.length,wasmBytes:buffer.byteLength,out:wasmPath}));
